import assert from "node:assert/strict"
import { planGenerationSubmission, stopGenerationTasks } from "../src/lib/generation-submission"
import { generationBatches, generationStats, generationSlots, generationViewBatches } from "../src/lib/generation-batches"
import type { GenerateTask } from "../src/lib/visual-shared"

const task = (i: number): GenerateTask => ({ id: `result-${i}`, sourceEntryId: `editor-${i}`, origin: "/simple", inputBatchId: "old-inputs", label: `提示词 ${i}`, ratio: "1:1", customSize: "", quality: "1k", count: 1, prompt: `原文${i}`, productImageDataUrl: "", status: "success", resultUrls: [`https://fixture.invalid/${i}.png`] })
const original = Array.from({ length: 5 }, (_, i) => task(i + 1)), snapshot = JSON.stringify(original)
const edited = { ...task(3), id: "editor-3", sourceEntryId: undefined, status: "queued" as const, resultUrls: [], prompt: "第三条修改后的完整提示词", ratio: "5:4", quality: "2k" as const }
const plan = planGenerationSubmission(original, [edited], original.map(t => t.sourceEntryId!), "new-inputs", () => "revision-2")
assert.equal(plan.related, true)
assert.equal(plan.incoming.length, 1)
assert.equal(plan.merged.length, 5)
assert.deepEqual(plan.merged.map(t => t.id), original.map(t => t.id))
for (const i of [0, 1, 3, 4]) assert.deepEqual(plan.merged[i], { ...original[i], generationBatchId: "old-inputs", generationEntryIds: original.map(t => t.sourceEntryId!) }, "旧格式仅补齐清单元数据，未启用内容/图片不改写")
assert.equal(plan.merged[2].prompt, edited.prompt)
assert.equal(plan.merged[2].ratio, "5:4")
assert.deepEqual(plan.merged[2].resultUrls, original[2].resultUrls, "新图返回前保留旧图")
assert.deepEqual(plan.merged[2].redraw?.pending, [0])
assert.equal(plan.merged[2].inputBatchId, "new-inputs")
assert.equal(generationBatches(plan.merged).length, 1, "素材批次变更不能隐藏其他四条")
assert.equal(generationStats(plan.merged).totalImages, 5)
const added = planGenerationSubmission(plan.merged, [{ ...edited, id: "editor-6" }], [...original.map(t => t.sourceEntryId!), "editor-6"], "add-input", () => "new-six")
assert.equal(added.merged.length, 6, "只启用新条目时也保留原清单")
const fresh = planGenerationSubmission(original, [{ ...edited, id: "fresh-editor" }], ["fresh-editor"], "fresh-input")
assert.equal(fresh.related, false, "全新清单独立，不能与旧批次累加")
assert.equal(fresh.merged.length, 1)
const reduced = planGenerationSubmission(plan.merged, [{ ...edited, id: "editor-1" }], ["editor-1"], "reduced-input", () => "reduced")
const reducedBatches = generationBatches(reduced.merged)
assert.equal(reducedBatches.at(-1)!.tasks.length, 1, "5框变1框不能继承另外4张旧卡")
assert.equal(reducedBatches.at(-1)!.tasks[0].sourceEntryId, "editor-1")
assert.deepEqual(reducedBatches[0].tasks.map(t => t.sourceEntryId), ["editor-2", "editor-3", "editor-4", "editor-5"], "移出清单的旧图只在历史查看")
assert.equal(reduced.merged.length, 5, "不删除旧图片或记录")
const reordered = planGenerationSubmission(plan.merged, [edited], ["editor-5", "editor-3", "editor-1"], "reordered", () => "reorder")
assert.deepEqual(generationBatches(reordered.merged).at(-1)!.tasks.map(t => t.sourceEntryId), ["editor-5", "editor-3", "editor-1"], "结果按当前编辑框顺序")
const sparse = planGenerationSubmission([], [edited], ["editor-1", "editor-2", "editor-3", "editor-4", "editor-5"], "sparse", () => "only-third")
const slots = generationSlots(generationBatches(sparse.merged)[0])
assert.equal(slots.length, 5)
assert.deepEqual(slots.map(slot => Boolean(slot.task)), [false, false, true, false, false], "只启用第3框仍显示第3位置，其余是不可执行占位")
assert.equal(sparse.incoming.length, 1)
const legacyBefore = JSON.stringify(original)
const repaired = generationViewBatches(original, ["editor-1"])
assert.equal(generationSlots(repaired.at(-1)!).length, 1)
assert.equal(repaired.at(-1)!.tasks.length, 1)
assert.equal(repaired[0].tasks.length, 4)
assert.equal(JSON.stringify(original), legacyBefore, "旧队列只读投影不保存/删除/重发")
assert.equal(generationViewBatches(original, null).at(-1)!.tasks.length, 5, "找不到可靠草稿时不猜测迁移")
assert.throws(() => planGenerationSubmission(original, [edited], ["editor-1"], "invalid"), /不在当前提示词清单/)
const states = [{ ...original[0], status: "running" as const }, { ...original[1], status: "queued" as const }, original[2]]
const stopped = stopGenerationTasks(states)
assert.equal(stopped[0].status, "interrupted")
assert.equal(stopped[1].status, "failed")
assert.equal(stopped[1].stoppedBeforeSend, true)
assert.equal(generationStats(stopped).stopped, 1)
assert.equal(generationStats(stopped).failed, 0)
assert.deepEqual(stopped[2], original[2])
assert.deepEqual(stopped.map(t => t.resultUrls), states.map(t => t.resultUrls))
assert.equal(JSON.stringify(original), snapshot)
console.log("PASS: 5条仅更新第3条/旧图兜底/位置与清单不变/添加条目/新清单独立/停止区分未发送和待确认（零网络）")
